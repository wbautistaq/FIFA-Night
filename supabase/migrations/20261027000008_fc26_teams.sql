-- FIFA Night · banco de equipos de EA SPORTS FC 26 con estrellas (5 grandes ligas + selecciones)
alter table fifa_teams add column if not exists stars numeric(2,1)
  check (stars is null or (stars between 0.5 and 5 and stars * 2 = trunc(stars * 2)));

-- Equipos propios de cada torneo: estrellas aproximadas a partir del rating
update fifa_teams set stars = least(5, greatest(0.5, round((rating - 66) / 4.0 * 2) / 2)) where stars is null;

-- Los equipos globales antiguos que ya están asignados en un torneo pasan a ser equipos propios de ese torneo,
-- así ningún sorteo existente pierde su equipo; el resto del banco antiguo se elimina.
update fifa_teams f set tournament_id = a.tournament_id
  from team_assignments a
 where a.team_id = f.id and f.tournament_id is null;
delete from fifa_teams where tournament_id is null;

